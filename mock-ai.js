const MockAI = {
  openings: [
    "Начнём с главного. Почему ты считаешь эту позицию обоснованной?",
    "Хорошо. Но твоё утверждение пока ничего не доказывает. Объясни причинную связь.",
    "Интересно. Теперь представь, что я полностью не согласен. Защити свой тезис.",
    "Ты сделал сильное заявление. Какие основания заставляют нас принять его?",
    "Допустим, твоя исходная посылка верна. Почему из неё следует твой вывод?"
  ],
  counters: [
    "Ты предполагаешь, что A автоматически приводит к B. Но где доказана именно эта связь?",
    "Твой аргумент может звучать убедительно, однако он зависит от одного спорного предположения. Почему мы должны его принять?",
    "Даже если принять твоё доказательство, оно не исключает противоположный вывод. Как ты ответишь на это?",
    "Ты ответил на следствие, но не на причину проблемы. Попробуй защитить именно исходный тезис.",
    "Это хороший тезис, но он пока недостаточно сравнивает альтернативы. Почему твой вариант лучше именно по критериям?",
    "Ты используешь общий принцип, но не показал, что он применим именно к этой ситуации.",
    "Представим исключение из твоего правила. Если твоя позиция перестаёт работать, насколько она действительно универсальна?",
    "Ты смешиваешь два разных вопроса: что возможно и что наиболее вероятно. Почему они здесь должны совпадать?"
  ],
  fallacies: [
    "ложная причинность",
    "поспешное обобщение",
    "ложная дихотомия",
    "подмена тезиса",
    "апелляция к большинству",
    "неподтверждённое предположение",
    "скользкий склон",
    "ad hominem"
  ],
  opening(topic, position, mode) {
    if (mode === "devil") {
      return `Тебе придётся защищать позицию «${position}» по теме: «${topic}». Я специально буду атаковать самые уязвимые места. Начинай.`;
    }
    if (mode === "cross") {
      return `Я буду задавать короткие вопросы и искать противоречия. Тема: «${topic}». Твоя позиция: ${position}. Первый вопрос: какое главное утверждение ты должен доказать?`;
    }
    if (mode === "logic") {
      return `Сегодня нас интересует не красноречие, а структура рассуждения. Тема: «${topic}». Защити позицию «${position}».`;
    }
    return `${this.random(this.openings)} Тема: «${topic}». Твоя позиция: ${position}.`;
  },
  nextRound(topic, position, round, mode) {
    if (mode === "cross") {
      return [
        "Хорошо. Теперь уточним определение. Что именно ты подразумеваешь под ключевым термином?",
        "Следующий вопрос: какое доказательство могло бы заставить тебя изменить мнение?",
        "Теперь я укажу на возможное исключение. Почему оно не разрушает твою позицию?",
        "Последний раунд: сформулируй самый сильный аргумент против собственной позиции и ответь на него."
      ][(round - 2) % 4];
    }
    return `Раунд ${round}. Предыдущий аргумент принят к рассмотрению. Теперь защити позицию глубже: не повторяй уже сказанное и ответь на возможное возражение.`;
  },
  analyze(text, context) {
    const lower = text.toLowerCase();
    const hasReason =
      /(потому что|так как|поскольку|следовательно|значит|поэтому|из-за|это приводит)/i.test(text);
    const hasEvidence =
      /(исследован|статист|процент|данн|пример|факт|источник|опыт|исследование|история)/i.test(text);
    const hasRebuttal =
      /(но|однако|возраж|контраргумент|можно сказать|критик|противник)/i.test(text);
    const hasAbsolute =
      /(всегда|никогда|все|никто|очевидно|безусловно|100%)/i.test(text);
    const hasComparison =
      /(лучше|хуже|более|менее|чем|по сравнению)/i.test(text);
    let logic = 48;
    let persuasion = 45;
    let evidence = 35;
    let rebuttal = 30;
    if (text.length > 120) logic += 10;
    if (text.length > 220) logic += 5;
    if (hasReason) logic += 18;
    if (hasEvidence) evidence += 35;
    if (hasRebuttal) rebuttal += 35;
    if (hasComparison) persuasion += 12;
    if (hasAbsolute) {
      logic -= 12;
      evidence -= 10;
    }
    if (/[?!]{2,}/.test(text)) persuasion -= 4;
    logic = this.clamp(logic);
    persuasion = this.clamp(persuasion);
    evidence = this.clamp(evidence);
    rebuttal = this.clamp(rebuttal);
    let grade;
    const total = (logic + persuasion + evidence + rebuttal) / 4;
    if (total >= 82) grade = "СИЛЬНЫЙ АРГУМЕНТ";
    else if (total >= 68) grade = "ХОРОШИЙ АРГУМЕНТ";
    else if (total >= 52) grade = "ЕСТЬ ОСНОВА";
    else grade = "СЛАБЫЙ АРГУМЕНТ";
    let feedback;
    if (hasEvidence && hasReason && hasRebuttal) {
      feedback =
        "Ты связал тезис с причиной, добавил опору и заранее затронул возможное возражение. Теперь следи, чтобы доказательство действительно подтверждало именно твой вывод.";
    } else if (!hasReason) {
      feedback =
        "Главная проблема — отсутствует явная причинная связь. Ты сообщил вывод, но оппонент может спросить: «Почему из этого следует именно такой результат?»";
    } else if (!hasEvidence) {
      feedback =
        "Логическая структура есть, но ей не хватает опоры. Добавь конкретный факт, пример, данные или объясни, на каком основании ты делаешь вывод.";
    } else if (!hasRebuttal) {
      feedback =
        "Аргумент сам по себе неплох, но ты оставил оппоненту свободное пространство для атаки. Предугадай сильнейшее возражение и ответь на него.";
    } else {
      feedback =
        "Аргумент работает, но его можно сделать точнее: отдели факты от предположений и покажи, почему альтернативное объяснение слабее.";
    }
    let improvement;
    if (logic < 60) {
      improvement = "Строй аргумент по цепочке: тезис → причина → доказательство → вывод.";
    } else if (evidence < 55) {
      improvement = "Добавляй проверяемые факты, цифры или конкретные примеры.";
    } else if (rebuttal < 55) {
      improvement = "Не жди возражения — сформулируй его сам и ответь заранее.";
    } else {
      improvement = "Усложняй аргументацию: рассматривай альтернативные объяснения и исключения.";
    }
    return {
      logic,
      persuasion,
      evidence,
      rebuttal,
      grade,
      feedback,
      improvement,
      fallacy: hasAbsolute ? this.random(this.fallacies) : null,
      pressureChange: Math.round((100 - logic) * .15)
    };
  },
  counter(text, topic, position, round, mode, analysis) {
    let counterText;
    if (analysis.logic >= 80 && analysis.evidence >= 70) {
      counterText =
        "Это уже серьёзнее. Тогда я не буду спорить с твоим доказательством напрямую. Вместо этого атакую предпосылку: почему именно этот критерий должен определять итог?";
    } else if (analysis.rebuttal < 50) {
      counterText =
        this.random(this.counters) +
        " Ты пока не ответил на эту линию атаки.";
    } else {
      counterText = this.random(this.counters);
    }
    return {
      text: counterText,
      emotion:
        analysis.logic >= 75 ? "surprised" :
        analysis.logic < 50 ? "confident" :
        "thinking",
      pressure:
        analysis.logic >= 75 ? -8 :
        analysis.logic < 50 ? 12 :
        5
    };
  },
  trainingAdvice(result) {
    const s = result.scores;
    if (s.rebuttal < 55)
      return "Следующая тренировка: научись сначала формулировать самый сильный аргумент против своей позиции.";
    if (s.evidence < 55)
      return "Следующая тренировка: используй конкретные данные и примеры вместо общих утверждений.";
    if (s.logic < 60)
      return "Следующая тренировка: каждый вывод должен иметь явно объяснённую связь с предыдущей посылкой.";
    return "Следующая тренировка: попробуй защищать позицию, одновременно рассматривая два сильных альтернативных объяснения.";
  },
  random(array) {
    return array[Math.floor(Math.random() * array.length)];
  },
  clamp(value) {
    return Math.max(0, Math.min(100, value));
  }
};
